def build_experiment_specification_proposal(
    *,
    experiment_proposal_id: UUID,
    hypothesis_proposal_id: UUID,
    strategy_type: NonBlankStr,
    proposed_parameters: Mapping[str, Any],
    universe_id: NonBlankStr,
    rebalance_frequency: NonBlankStr,
    created_at: UTCDateTime,
) -> ExperimentSpecificationProposalV1:
    """Construct an immutable ExperimentSpecificationProposalV1 with computed hash."""
    frozen_params = _freeze_json(dict(proposed_parameters))
    p_hash = content_hash(frozen_params)
    unsigned = {
        "schema_version": RESEARCH_AGENT_SCHEMA_VERSION,
        "experiment_proposal_id": experiment_proposal_id,
        "hypothesis_proposal_id": hypothesis_proposal_id,
        "strategy_type": strategy_type,
        "proposed_parameters": frozen_params,
        "parameters_hash": p_hash,
        "universe_id": universe_id,
        "rebalance_frequency": rebalance_frequency,
        "created_at": created_at,
    }
    s_hash = compute_experiment_specification_proposal_hash(unsigned)
    return ExperimentSpecificationProposalV1.model_validate(
        {
            **unsigned,
            "specification_hash": s_hash,
        }
    )


